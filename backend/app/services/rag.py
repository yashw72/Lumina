DIAGRAM_EXPLANATION_INSTRUCTION = (
    "You are DocuMentor AI, an expert educational study assistant. "
    "A visual concept diagram illustrating this topic has already been generated by the visual rendering system "
    "and is displayed directly above your response. "
    "DO NOT apologize. DO NOT say you cannot create, output, or display images or diagrams. "
    "DO NOT mention 'mental diagrams'. "
    "Directly explain the technical components, relationships, and key exam takeaways for the requested concept."
)


def clean_disclaimers(text: str) -> str:
    """Removes LLM disclaimers about not being able to output images or generate diagrams."""
    disclaimer_patterns = [
        r"(?i)while\s+i\s+cannot\s+(directly\s+)?(output|generate|create|produce|display)\s+(image|diagram)[^\n.]*[\n.]*",
        r"(?i)as\s+an?\s+(ai|language\s+model)[^\n.]*cannot\s+(output|generate|create|produce|display)\s+(image|diagram)[^\n.]*[\n.]*",
        r"(?i)i\s+cannot\s+(directly\s+)?(output|generate|create|produce)\s+image\s+files[^\n.]*[\n.]*",
        r"(?i)this\s+structured\s+text\s+functions\s+as\s+a\s+[\"']mental\s+diagram[\"'][^\n.]*[\n.]*",
    ]
    cleaned = text
    for p in disclaimer_patterns:
        cleaned = re.sub(p, "", cleaned)
    return cleaned.strip()


def is_incomplete_prompt(prompt: str) -> bool:
    """Detects prompts that are bare verbs or incomplete prefixes without a subject/topic."""
    p = prompt.strip().lower()
    bare_verbs = {
        "explain",
        "explain.",
        "explain!",
        "explain this",
        "describe",
        "illustrate",
        "draw",
        "draw diagram",
        "diagram",
        "visualize",
        "image",
        "/image",
        "show",
    }
    if p in bare_verbs:
        return True

    incomplete_endings = (
        "illustrating",
        "illustrating:",
        "showing",
        "showing:",
        "explaining the process of",
        "components of",
        "diagram of",
        "image of",
    )
    for ending in incomplete_endings:
        if p.endswith(ending):
            return True

    return False


def is_image_request(question: str, is_image: bool = False) -> bool:
    """Detects whether a student prompt is explicitly requesting an image or diagram."""
    if is_image:
        return True
    q = question.strip().lower()
    patterns = [
        r"^/image\b",
        r"\bgenerate\s+(an?\s+)?(image|diagram|chart|flowchart|illustration|visual)\b",
        r"\b(draw|illustrate|create)\s+(an?\s+)?(image|diagram|chart|flowchart|illustration|visual)\b",
        r"\b(show|provide)\s+(an?\s+)?(image|diagram|chart|flowchart|visual)\b",
        r"\bvisualize\b",
    ]
    return any(re.search(p, q) for p in patterns)


def answer_question(
    db: Session,
    question: str,
    document_ids: Optional[List[int]] = None,
    session_id: Optional[str] = None,
    is_image: bool = False,
    user_id: Optional[int] = None,
) -> Dict[str, Any]:
    """
    RAG QA pipeline:
    1. Manage or create chat session and verify session ownership per user.
    2. Resolve allowed documents for the user (404 if not owned; friendly fallback if none uploaded).
    3. Check for short follow-up questions and enrich retrieval query.
    4. Guard against incomplete bare prompts.
    5. Search vector store with explicit document_ids filter.
    6. Construct context-grounded prompt and query LLM.
    """
    settings = get_settings()

    # 1. Manage ChatSession and enforce ownership
    session = None
    if session_id:
        session = db.query(ChatSession).filter(ChatSession.id == session_id).first()
        if session and user_id is not None and session.user_id is not None and session.user_id != user_id:
            raise HTTPException(
                status_code=status.HTTP_404_NOT_FOUND,
                detail=f"Session with ID '{session_id}' not found.",
            )
    if not session:
        session = ChatSession(
            id=session_id if session_id else str(uuid.uuid4()),
            user_id=user_id,
        )
        db.add(session)
        db.commit()
        db.refresh(session)

    # Record user message
    user_msg = ChatMessage(
        session_id=session.id,
        role="user",
        content=question,
        sources_json=None,
    )
    db.add(user_msg)
    # 2. Check for follow-up question
    retrieval_query = question
    words = question.strip().split()
    if len(words) < 6:
        prev_user_msg = (
            db.query(ChatMessage)
            .filter(
                ChatMessage.session_id == session.id,
                ChatMessage.role == "user",
                ChatMessage.id != user_msg.id,
            )
            .order_by(ChatMessage.created_at.desc())
            .first()
        )
        if prev_user_msg and prev_user_msg.content:
            retrieval_query = f"{prev_user_msg.content} {question}"
            logger.info("Enriched follow-up retrieval query: '%s'", retrieval_query)

    # Incomplete prompt guardrail (e.g., bare 'Explain' or unfinished prompt prefix)
    if is_incomplete_prompt(retrieval_query):
        answer = (
            "Please specify what concept or topic you would like me to explain or visualize "
            "from your uploaded documents (for example: *'Explain the four Coffman conditions for deadlock'* "
            "or *'Draw a diagram of the TCP 3-way handshake'*)."
        )
        assistant_msg = ChatMessage(
            session_id=session.id,
            role="assistant",
            content=answer,
            sources_json=json.dumps([]),
            image_url=None,
        )
        db.add(assistant_msg)
        db.commit()

        return {
            "session_id": session.id,
            "answer": answer,
            "sources": [],
            "image_url": None,
        }

    # 3. Resolve allowed document IDs for this user
    user_ready_query = db.query(Document.id).filter(Document.status == "ready")
    if user_id is not None:
        user_ready_query = user_ready_query.filter(Document.user_id == user_id)
    user_ready_ids = [r[0] for r in user_ready_query.all()]

    if document_ids:
        missing_ids = set(document_ids) - set(user_ready_ids)
        if missing_ids:
            raise HTTPException(
                status_code=status.HTTP_404_NOT_FOUND,
                detail="Document not found.",
            )
        resolved_doc_ids = list(document_ids)
    else:
        if not user_ready_ids:
            friendly_answer = "I could not find this in your uploaded documents. Upload a document first."
            assistant_msg = ChatMessage(
                session_id=session.id,
                role="assistant",
                content=friendly_answer,
                sources_json=json.dumps([]),
                image_url=None,
            )
            db.add(assistant_msg)
            db.commit()
            return {
                "session_id": session.id,
                "answer": friendly_answer,
                "sources": [],
                "image_url": None,
            }
        resolved_doc_ids = user_ready_ids

    # 4. Vector search (always pass explicit resolved document IDs)
    q_emb = embeddings.embed_query(retrieval_query)
    chunks = vector_store.query(
        query_embedding=q_emb,
        top_k=settings.TOP_K,
        document_ids=resolved_doc_ids,
    )

    image_mode = is_image_request(question, is_image)

    # 4. Guardrail: no chunks or relevance score below threshold
    if not chunks or max(c["score"] for c in chunks) < 0.25:
        if image_mode:
            img_result = image_gen.generate_study_image(question)
            img_url = img_result.get("image_url")
            raw_answer = llm.generate(
                prompt=(
                    f"Topic requested: '{question}'.\n"
                    f"Provide a clear, pedagogical explanation of this concept, breaking down its key components, "
                    f"structure, and significance for exams. Use Markdown formatting with bold concepts."
                ),
                system_instruction=DIAGRAM_EXPLANATION_INSTRUCTION,
                temperature=0.3,
            )
            answer = clean_disclaimers(raw_answer)
            sources: List[Dict[str, Any]] = []

            assistant_msg = ChatMessage(
                session_id=session.id,
                role="assistant",
                content=answer,
                sources_json=json.dumps(sources),
                image_url=img_url,
            )
            db.add(assistant_msg)
            db.commit()

            return {
                "session_id": session.id,
                "answer": answer,
                "sources": sources,
                "image_url": img_url,
            }

        answer = "I could not find this information in your uploaded documents."
        sources: List[Dict[str, Any]] = []

        assistant_msg = ChatMessage(
            session_id=session.id,
            role="assistant",
            content=answer,
            sources_json=json.dumps(sources),
            image_url=None,
        )
        db.add(assistant_msg)
        db.commit()

        return {
            "session_id": session.id,
            "answer": answer,
            "sources": sources,
            "image_url": None,
        }

    # 5. Build prompt with context and history
    past_messages = (
        db.query(ChatMessage)
        .filter(ChatMessage.session_id == session.id, ChatMessage.id != user_msg.id)
        .order_by(ChatMessage.created_at.asc())
        .all()
    )
    recent_history = past_messages[-4:]

    history_text = ""
    if recent_history:
        history_text = "\n".join(f"{m.role.capitalize()}: {m.content}" for m in recent_history)
        history_text = f"Recent conversation history:\n{history_text}\n\n"

    context_blocks = []
    for i, c in enumerate(chunks, start=1):
        context_blocks.append(
            f"[Context {i}] (Source: {c['filename']}, Page {c['page']}):\n{c['text']}"
        )
    context_text = "\n\n".join(context_blocks)

    generated_image_url: Optional[str] = None
    if image_mode:
        img_result = image_gen.generate_study_image(question, context=context_text)
        generated_image_url = img_result.get("image_url")
        full_prompt = (
            f"{history_text}"
            f"Provided study context:\n{context_text}\n\n"
            f"Student requested an educational diagram/illustration: {question}\n\n"
            f"Explain the architectural components, concepts, and relationships depicted in this visual diagram based on the study documents. Structure the explanation with key components and takeaway points.\n\n"
            f"Answer:"
        )
    else:
        full_prompt = (
            f"{history_text}"
            f"Provided study context:\n{context_text}\n\n"
            f"Student question: {question}\n\n"
            f"Answer:"
        )

    # Call LLM
    instruction_to_use = DIAGRAM_EXPLANATION_INSTRUCTION if image_mode else SYSTEM_INSTRUCTION
    raw_answer = llm.generate(
        prompt=full_prompt,
        system_instruction=instruction_to_use,
        temperature=0.2,
    )
    answer = clean_disclaimers(raw_answer) if image_mode else raw_answer

    # Deduplicate sources
    seen_sources = set()
    sources = []
    for c in chunks:
        key = (c["document_id"], c["page"], c["text"][:60])
        if key not in seen_sources:
            seen_sources.add(key)
            sources.append({
                "document_id": c["document_id"],
                "filename": c["filename"],
                "page": c["page"],
                "snippet": c["text"][:200].strip(),
                "score": round(c["score"], 2),
            })

    # Persist assistant response
    assistant_msg = ChatMessage(
        session_id=session.id,
        role="assistant",
        content=answer,
        sources_json=json.dumps(sources),
        image_url=generated_image_url,
    )
    db.add(assistant_msg)
    db.commit()

    return {
        "session_id": session.id,
        "answer": answer,
        "sources": sources,
        "image_url": generated_image_url,
    }
